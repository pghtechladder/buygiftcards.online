// Regenerates src/lib/zendit-offers-au.generated.ts from the LIVE Zendit Australia (AU / .au) voucher catalog
// (GET /v1/vouchers/offers?country=AU), mapping each brand in src/lib/brands-au.ts to its live Zendit
// offerId(s) and requiredFields. Face value is Zendit's `send` amount in AUD (currencyDivisor = 100).
//
//   ZENDIT_KEY=<key> node scripts/generate-zendit-au-map.mjs
//
import fs from 'fs';

let KEY = process.env.ZENDIT_KEY || process.env.ZENDIT_API_KEY;
if (!KEY && fs.existsSync('env-au')) {
  const m = fs.readFileSync('env-au', 'utf8').match(/ZENDIT_API_KEY="([^"]+)"/);
  if (m) KEY = m[1];
}
if (!KEY) { console.error('Set ZENDIT_KEY or ZENDIT_API_KEY in env-au'); process.exit(2); }

const all = [];
for (let off = 0; ; off += 1000) {
  const url = 'https://api.zendit.io/v1/vouchers/offers?_limit=1000&_offset=' + off + '&country=AU';
  const r = await fetch(url, {
    headers: { Authorization: 'Bearer ' + KEY },
  });
  const d = await r.json();
  all.push(...(d.list || []));
  if (!d.list || d.list.length < 1000) break;
}
console.log(`Fetched ${all.length} offers from Zendit AU`);
const offers = all.filter(o => o.enabled !== false);

const norm = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]/g, '');
const byBrand = new Map();
for (const o of offers) {
  const k = norm(o.brand);
  if (!byBrand.has(k)) byBrand.set(k, []);
  byBrand.get(k).push(o);
}

const ALIAS = {
  amazon: 'Amazon',
  target: 'Target',
  ubereats: 'UberEats',
  doordash: 'DoorDash',
  asos: 'Asos',
  hm: 'HM',
  ticketmaster: 'TicketMaster',
  uber: 'Uber',
  globalhotel: 'GlobalHotel',
  globalexperiences: 'Globalexperiences',
};

const faceOf = o => {
  const x = o.send || o.price || {};
  const div = x.currencyDivisor || 100;
  return x.fixed != null ? { fixed: x.fixed / div } : { min: x.min / div, max: x.max / div };
};
const isFace = n => Number.isInteger(n) && n > 0;

const src = fs.readFileSync('src/lib/brands-au.ts', 'utf8');
const house = ['buygiftcards', 'one4all', 'holidayfavorites'];
const rows = [...src.matchAll(/slug:\s*"([^"]+)",\s*name:\s*"([^"]+)"/g)].map(m => ({
  slug: m[1],
  name: m[2].replace(/\\u0026/g, '&'),
}));

const specs = {};
const unmatched = [];

for (const { slug, name } of rows) {
  if (house.includes(slug)) continue;
  const cands = [ALIAS[slug] && norm(ALIAS[slug]), norm(name), slug, slug.replace(/australia$/, '')].filter(Boolean);
  const key = cands.find(c => byBrand.has(c)) || [...byBrand.keys()].find(k => k.includes(slug));
  if (!key) { unmatched.push(`${slug} ("${name}")`); continue; }
  const list = byBrand.get(key);
  const spec = {};
  const fixed = {};
  for (const o of list) {
    const f = faceOf(o);
    if (o.priceType === 'RANGE' || f.min != null) {
      if (isFace(f.min) && isFace(f.max)) spec.rangeOfferId = o.offerId;
    } else if (isFace(f.fixed)) {
      if (fixed[f.fixed]) {
        const pref = id => (/EGIFT|GIFT/i.test(id) ? 0 : 1);
        if (pref(o.offerId) < pref(fixed[f.fixed])) fixed[f.fixed] = o.offerId;
      } else {
        fixed[f.fixed] = o.offerId;
      }
    }
  }
  if (Object.keys(fixed).length) spec.fixedOffers = fixed;
  const rf = list.find(o => (o.requiredFields || []).length)?.requiredFields;
  if (rf) spec.requiredFields = rf.map(f => (typeof f === 'string' ? f : f.key || f.name));
  if (spec.rangeOfferId || spec.fixedOffers) specs[slug] = spec;
  else unmatched.push(`${slug} ("${name}") [no whole-dollar AUD offers]`);
}

fs.writeFileSync(
  'src/lib/zendit-offers-au.generated.ts',
  `// AUTO-GENERATED by scripts/generate-zendit-au-map.mjs from the live Zendit Australia (AU / .au) voucher catalog
// (GET /v1/vouchers/offers?country=AU). Do not edit by hand. Face value = Zendit \`send\` amount in AUD.
import type { ZenditOfferSpec } from "./giftcard-provider";

export const GENERATED_ZENDIT_AU_OFFERS: Record<string, ZenditOfferSpec> = ${JSON.stringify(specs, null, 2)};
`
);

console.log(`Generated src/lib/zendit-offers-au.generated.ts (${Object.keys(specs).length} Australia brands mapped)`);
if (unmatched.length) console.log('Unmatched AU brands:', unmatched);
