// Regenerates src/lib/zendit-offers-ca.generated.ts from the LIVE Zendit Canada (CA) voucher catalog,
// then syncs brand denominations / min / max / fixedOnly / discountPercent in src/lib/brands-ca.ts.
// Face value is Zendit's `send` amount in CAD (currencyDivisor = 100).
//
//   ZENDIT_KEY=<key> node scripts/generate-zendit-ca-map.mjs
//
import fs from 'fs';

let KEY = process.env.ZENDIT_KEY || process.env.ZENDIT_API_KEY;
if (!KEY && fs.existsSync('env-ca')) {
  const m = fs.readFileSync('env-ca', 'utf8').match(/ZENDIT_API_KEY="([^"]+)"/);
  if (m) KEY = m[1];
}
if (!KEY) { console.error('Set ZENDIT_KEY or ZENDIT_API_KEY in env-ca'); process.exit(2); }

const all = [];
for (let off = 0; ; off += 1000) {
  const url = 'https://api.zendit.io/v1/vouchers/offers?_limit=1000&_offset=' + off + '&country=CA';
  const r = await fetch(url, {
    headers: { Authorization: 'Bearer ' + KEY },
  });
  const d = await r.json();
  all.push(...(d.list || []));
  if (!d.list || d.list.length < 1000) break;
}
console.log(`Fetched ${all.length} offers from Zendit CA`);
const offers = all.filter(o => o.enabled !== false);

const norm = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]/g, '');
const byBrand = new Map();
for (const o of offers) {
  const k = norm(o.brand);
  if (!byBrand.has(k)) byBrand.set(k, []);
  byBrand.get(k).push(o);
}

const ALIAS = {
  aeo: 'AmericanEagle',
  basspro: 'BassProShops',
  cabelas: 'Cabela',
  kobo: 'Kobo',
  petrocanada: 'PetroCanada',
  columbiasportswear: 'ColumbiaSportswear',
  bananarepublic: 'BananaRepublic',
  bostonpizza: 'BostonPizza',
  biermarkt: 'BierMarkt',
  googleplay: 'GooglePlay',
  kigsogames: 'KigsoGames',
  redlobster: 'RedLobster',
  tqgamecard: 'TQGameCard',
  ubereats: 'UberEats',
};

const faceOf = o => {
  const x = o.send || o.price || {};
  const div = x.currencyDivisor || 100;
  return x.fixed != null ? { fixed: x.fixed / div } : { min: x.min / div, max: x.max / div };
};
const isFace = n => Number.isInteger(n) && n > 0;

const src = fs.readFileSync('src/lib/brands-ca.ts', 'utf8');
const house = ['buygiftcards', 'one4all', 'holidayfavorites'];
const rows = [...src.matchAll(/slug:\s*"([^"]+)",\s*name:\s*"([^"]+)"/g)].map(m => ({
  slug: m[1],
  name: m[2].replace(/\\u0026/g, '&'),
}));

const specs = {};
const unmatched = [];
const used = new Set();

for (const { slug, name } of rows) {
  if (house.includes(slug)) continue;
  const cands = [ALIAS[slug] && norm(ALIAS[slug]), norm(name), slug, slug.replace(/canada$/, '')].filter(Boolean);
  const key = cands.find(c => byBrand.has(c)) || [...byBrand.keys()].find(k => k.includes(slug.replace(/canada$/, '')));
  if (!key) { unmatched.push(`${slug} ("${name}")`); continue; }
  used.add(key);
  const list = byBrand.get(key);
  const spec = {};
  const fixed = {};
  const collisions = [];
  for (const o of list) {
    const f = faceOf(o);
    if (o.priceType === 'RANGE' || f.min != null) {
      if (isFace(f.min) && isFace(f.max)) spec.rangeOfferId = o.offerId;
    } else if (isFace(f.fixed)) {
      if (fixed[f.fixed]) {
        const pref = id => (/EGIFT|GIFT/i.test(id) ? 0 : 1);
        if (pref(o.offerId) < pref(fixed[f.fixed])) fixed[f.fixed] = o.offerId;
        collisions.push(`${f.fixed}: ${o.offerId}`);
      } else fixed[f.fixed] = o.offerId;
    }
  }
  if (Object.keys(fixed).length) spec.fixedOffers = fixed;
  const rf = list.find(o => (o.requiredFields || []).length)?.requiredFields;
  if (rf) spec.requiredFields = rf.map(f => (typeof f === 'string' ? f : f.key || f.name));
  if (collisions.length) console.log(`NOTE ${slug}: multiple CA offers for same face value -> ${collisions.join(', ')}; using`, JSON.stringify(fixed));
  if (spec.rangeOfferId || spec.fixedOffers) specs[slug] = spec;
  else unmatched.push(`${slug} ("${name}") [no whole-dollar CAD offers]`);
}

fs.writeFileSync(
  'src/lib/zendit-offers-ca.generated.ts',
  `// AUTO-GENERATED by scripts/generate-zendit-ca-map.mjs from the live Zendit Canada (CA) voucher catalog
// (GET /v1/vouchers/offers?country=CA). Do not edit by hand. Face value = Zendit \`send\` amount in CAD.
import type { ZenditOfferSpec } from "./giftcard-provider";

export const GENERATED_ZENDIT_CA_OFFERS: Record<string, ZenditOfferSpec> = ${JSON.stringify(specs, null, 2)};
`
);

console.log(`Generated src/lib/zendit-offers-ca.generated.ts (${Object.keys(specs).length} Canada brands mapped)`);
if (unmatched.length) console.log('Unmatched CA brands:', unmatched);
