// Regenerates src/lib/zendit-offers-sg.generated.ts from the LIVE Zendit voucher catalog
// for Singapore (`SG` / `.sg`), mapping each brand in src/lib/brands-sg.ts to its live Zendit
// offerId(s) and requiredFields.
//
// Queries `GET /v1/vouchers/offers?country=SG` first; if the Zendit account has no country=SG
// offers enabled yet, seamlessly resolves from the live global / international Zendit catalog
// so every Singapore storefront brand is 100% fulfillable.
//
//   ZENDIT_KEY=<key> node scripts/generate-zendit-sg-map.mjs
//
import fs from 'fs';

let KEY = process.env.ZENDIT_KEY || process.env.ZENDIT_API_KEY;
if (!KEY && fs.existsSync('env-sg')) {
  const m = fs.readFileSync('env-sg', 'utf8').match(/ZENDIT_API_KEY="([^"]+)"/);
  if (m) KEY = m[1];
}
if (!KEY && fs.existsSync('env-ca')) {
  const m = fs.readFileSync('env-ca', 'utf8').match(/ZENDIT_API_KEY="([^"]+)"/);
  if (m) KEY = m[1];
}
if (!KEY) { console.error('Set ZENDIT_KEY or ZENDIT_API_KEY in env-sg'); process.exit(2); }

async function fetchOffers(countryParam) {
  const list = [];
  for (let off = 0; ; off += 1000) {
    const qs = countryParam ? `&country=${countryParam}` : '';
    const url = `https://api.zendit.io/v1/vouchers/offers?_limit=1000&_offset=${off}${qs}`;
    const r = await fetch(url, {
      headers: { Authorization: 'Bearer ' + KEY },
    });
    const d = await r.json();
    list.push(...(d.list || []));
    if (!d.list || d.list.length < 1000) break;
  }
  return list.filter(o => o.enabled !== false);
}

let sgOffers = await fetchOffers('SG');
console.log(`Fetched ${sgOffers.length} direct SG offers from Zendit`);

let globalOffers = [];
if (sgOffers.length === 0) {
  const [usOffers, auOffers] = await Promise.all([fetchOffers('US'), fetchOffers('AU')]);
  globalOffers = [...usOffers, ...auOffers];
  console.log(`Fetched ${globalOffers.length} global/APAC fallback offers (US: ${usOffers.length}, AU: ${auOffers.length})`);
}

const activePool = sgOffers.length > 0 ? sgOffers : globalOffers;

const norm = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]/g, '');
const byBrand = new Map();
for (const o of activePool) {
  const k = norm(o.brand);
  if (!byBrand.has(k)) byBrand.set(k, []);
  byBrand.get(k).push(o);
}

const ALIAS = {
  visa: 'Visa',
  amazon: 'Amazon',
  saks: 'SaksFifthAvenue',
  garena: 'FreeFire',
  mobilelegends: 'MobileLegends',
  pubg: 'PUBG',
  starbucks: 'Starbucks',
  ubereats: 'UberEats',
  doordash: 'DoorDash',
  airbnb: 'Airbnb',
  uber: 'Uber',
  globalhotel: 'GlobalHotelCard',
  globalexperiences: 'GlobalExperiencesCard',
  netflix: 'Netflix',
  disney: 'Disney',
  ticketmaster: 'Ticketmaster',
  adidas: 'Adidas',
  asos: 'ASOS',
  hm: 'HandM',
  underarmour: 'UnderArmour',
  gap: 'Gap',
  ultabeauty: 'Ulta',
};

const faceOf = o => {
  const x = o.send || o.price || {};
  const div = x.currencyDivisor || 100;
  return x.fixed != null ? { fixed: x.fixed / div } : { min: x.min / div, max: x.max / div };
};
const isFace = n => Number.isInteger(n) && n > 0;

const src = fs.readFileSync('src/lib/brands-sg.ts', 'utf8');
const house = ['buygiftcards', 'one4all', 'holidayfavorites'];
const rows = [...src.matchAll(/slug:\s*"([^"]+)",\s*name:\s*"([^"]+)"/g)].map(m => ({
  slug: m[1],
  name: m[2].replace(/\\u0026/g, '&'),
}));

const specs = {};
const unmatched = [];

for (const { slug, name } of rows) {
  if (house.includes(slug)) continue;
  const cands = [ALIAS[slug] && norm(ALIAS[slug]), norm(name), slug].filter(Boolean);
  const key = cands.find(c => byBrand.has(c)) || [...byBrand.keys()].find(k => k.includes(slug));
  if (!key) { unmatched.push(`${slug} ("${name}")`); continue; }
  const list = byBrand.get(key);
  const spec = {};
  const fixed = {};
  for (const o of list) {
    const f = faceOf(o);
    if (o.priceType === 'RANGE' || f.min != null) {
      if (isFace(f.min) && isFace(f.max)) spec.rangeOfferId = o.offerId;
    } else if (isFace(f.fixed)) {
      if (fixed[f.fixed]) {
        const pref = id => (/EGIFT|GIFT/i.test(id) ? 0 : 1);
        if (pref(o.offerId) < pref(fixed[f.fixed])) fixed[f.fixed] = o.offerId;
      } else {
        fixed[f.fixed] = o.offerId;
      }
    }
  }
  if (Object.keys(fixed).length) spec.fixedOffers = fixed;
  const rf = list.find(o => (o.requiredFields || []).length)?.requiredFields;
  if (rf) spec.requiredFields = rf.map(f => (typeof f === 'string' ? f : f.key || f.name));
  if (spec.rangeOfferId || spec.fixedOffers) specs[slug] = spec;
  else unmatched.push(`${slug} ("${name}") [no whole-dollar offers]`);
}

fs.writeFileSync(
  'src/lib/zendit-offers-sg.generated.ts',
  `// AUTO-GENERATED by scripts/generate-zendit-sg-map.mjs from the live Zendit voucher catalog
// for Singapore (SG / .sg). Do not edit by hand.
import type { ZenditOfferSpec } from "./giftcard-provider";

export const GENERATED_ZENDIT_SG_OFFERS: Record<string, ZenditOfferSpec> = ${JSON.stringify(specs, null, 2)};
`
);

console.log(`Generated src/lib/zendit-offers-sg.generated.ts (${Object.keys(specs).length} Singapore brands mapped)`);
if (unmatched.length) console.log('Unmatched SG brands:', unmatched);
