function requireEnv(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is not set — required for TangoCardProvider`);
  return value;
}

export class TangoCardProvider implements GiftCardProvider {
  private baseUrl: string;
  private platformName: string;
  private platformKey: string;
  private accountIdentifier: string;
  private customerIdentifier: string;

  constructor() {
    // Sandbox vs production is just a different base URL in Tango's API —
    // defaults to sandbox so you can't accidentally hit production by
    // forgetting to set this.
    this.baseUrl = (process.env.TANGO_API_BASE_URL || "https://integration-api.tangocard.com/raas/v2").replace(/\/+$/, "");
    this.platformName = requireEnv("TANGO_PLATFORM_NAME");
    this.platformKey = requireEnv("TANGO_PLATFORM_KEY");
    this.accountIdentifier = requireEnv("TANGO_ACCOUNT_IDENTIFIER");
    this.customerIdentifier = requireEnv("TANGO_CUSTOMER_IDENTIFIER");
  }

  async issue({ brandSlug, amountCents }: { brandSlug: string; amountCents: number }): Promise<IssuedCard> {
    const mapping = BRAND_TO_TANGO_UTID[brandSlug];
    if (!mapping) {
      throw new Error(
        `No Tango Card utid mapped for brand "${brandSlug}". Run \`npm run tango:match\` and add it to BRAND_TO_TANGO_UTID.`
      );
    }

    let utid: string;
    if (typeof mapping === "string") {
      utid = mapping; // variable-value card, works for any amount
    } else {
      const dollars = amountCents / 100;
      const found = mapping[dollars];
      if (!found) {
        throw new Error(
          `Brand "${brandSlug}" has no Tango utid for $${dollars} — available: ${Object.keys(mapping).join(", ")}`
        );
      }
      utid = found;
    }

    const auth = Buffer.from(`${this.platformName}:${this.platformKey}`).toString("base64");
    const tangoPayload = {
      accountIdentifier: this.accountIdentifier,
      customerIdentifier: this.customerIdentifier,
      amount: amountCents / 100,
      utid,
      sendEmail: false, // we deliver the code ourselves via our own email
    };
    const { res, data, rawText } = await loggedFetch({
      process: `TangoCardProvider.issue(${brandSlug})`,
      url: `${this.baseUrl}/orders`,
      method: "POST",
      headers: {
        Authorization: `Basic ${auth}`,
        "Content-Type": "application/json",
      },
      bodyObj: tangoPayload,
    });

    if (!res.ok) {
      throw new Error(`Tango Card order failed (${res.status}): ${rawText}`);
    }
    // Verified against a real sandbox order (Starbucks, $5): the response
    // has reward.credentialList = [{ label, value, type, credentialType }],
    // and credentialType varies by brand/reward — card-number brands use
    // "cardNumber"/"pin", others (confirmed: Starbucks) deliver a
    // "redemptionUrl" instead with no PIN at all. Handle both rather than
    // assuming one shape.
    type Credential = { credentialType?: string; value?: string };
    const credentialList: Credential[] = data?.reward?.credentialList ?? [];

    const cardNumber = credentialList.find((c) => c.credentialType === "cardNumber")?.value;
    const pin = credentialList.find((c) => c.credentialType === "pin")?.value ?? "";
    const redemptionUrl = credentialList.find(
      (c) => c.credentialType === "redemptionUrl" || c.credentialType === "claimUrl"
    )?.value;

    const code = cardNumber ?? redemptionUrl ?? credentialList[0]?.value;
    if (!code) {
      throw new Error(`Tango Card order succeeded but no redeemable code was found in the response: ${JSON.stringify(data)}`);
    }

    return { code, pin, isDemo: false };
  }
}

// Per-brand, not global: only ~66 of our 165 catalog brands have a Tango
// utid mapped (sandbox catalog is a curated subset — see the comment on
// BRAND_TO_TANGO_UTID). A single global switch would mean checkout starts
// throwing entirely for every unmapped brand the moment Tango is
// configured. Instead: use Tango when a brand is mapped, fall back to Demo
// (loudly logged) when it isn't — the resulting code is still marked
// isDemo, which the order detail page and email already surface clearly.
class HybridGiftCardProvider implements GiftCardProvider {
  constructor(
    private tango: GiftCardProvider,
    private demo: GiftCardProvider
  ) {}

  async issue(params: { brandSlug: string; amountCents: number }): Promise<IssuedCard> {
    if (BRAND_TO_TANGO_UTID[params.brandSlug]) {
      try {
        return await this.tango.issue(params);
      } catch (err) {
        const msg = err instanceof Error ? err.message : String(err);
        console.warn(
          `[giftcard-provider] Tango issue failed for "${params.brandSlug}" (${msg}) — issuing demo code fallback.`
        );
        return this.demo.issue(params);
      }
    }
    console.warn(
      `[giftcard-provider] "${params.brandSlug}" has no Tango mapping — issuing a non-redeemable demo code instead of real fulfillment.`
    );
    return this.demo.issue(params);
  }
}

// ---------------------------------------------------------------------------
// ZenditProvider — Primary live gift-card fulfillment provider
// ---------------------------------------------------------------------------
// Uses Zendit's Prepaid-as-a-Service REST API (https://developers.zendit.io/api/).
// Base URL: https://api.zendit.io/v1
// Authentication: Authorization: Bearer <ZENDIT_API_KEY>
//
// Required env vars:
//   ZENDIT_API_KEY       — Sandbox (`sand_...`) or Production API secret key
//   ZENDIT_API_BASE_URL  — (optional) defaults to https://api.zendit.io/v1
//   ZENDIT_USERNAME      — (optional) account username / email (e.g. sri@techladder.io)
//
// How it works:
//   1. House / Multi-Brand choice cards (`buygiftcards`, `one4all`, `holidayfavorites`)
//      issue a 16-digit BuyGiftCards.online Card Number + 8-digit PIN redeemable on `/redeem`.
//   2. Mapped Zendit catalog brands (`BRAND_TO_ZENDIT_OFFER`) submit `POST /v1/vouchers/purchases`
//      with `offerId`, `transactionId`, `fields` (auto-populated for brands requiring
//      `recipient.firstName`, `recipient.lastName`, `recipient.email`, etc.), and `value`
//      (`{ type: "ZEND", value: amountCents }` for RANGE offers).
//   3. Polls `GET /v1/vouchers/purchases/{transactionId}` until `status === "DONE"` (typically
//      < 1 second) and extracts `receipt.redemptionUrl` or `receipt.voucherId` + `receipt.epin`.
// ---------------------------------------------------------------------------

export type ZenditOfferSpec = {
  /** RANGE offerId accepting any dollar amount between min and max */
  rangeOfferId?: string;
  /** FIXED denomination map: dollar amount -> exact Zendit offerId */
  fixedOffers?: Record<number, string>;
  /** Required recipient/sender fields declared by Zendit for this brand */
  requiredFields?: string[];
};

// Offer mapping now comes from the live Zendit catalog: see src/lib/zendit-offers.generated.ts
// (regenerate with scripts/generate-zendit-map.mjs, verify with scripts/audit-catalog.mjs).
// Only house cards are declared by hand — they are redeemed later on /redeem.
export const BRAND_TO_ZENDIT_OFFER: Record<string, ZenditOfferSpec> = {
  buygiftcards: { rangeOfferId: "HOUSE_SWAP" },
  one4all: { rangeOfferId: "HOUSE_SWAP" },
  holidayfavorites: { rangeOfferId: "HOUSE_SWAP" },
};

function buildZenditRequiredFields(
  requiredKeys?: string[],
  context?: { recipientEmail?: string; recipientName?: string; senderName?: string }
): { key: string; value: string }[] {
  if (!requiredKeys || requiredKeys.length === 0) return [];
  const defaultEmail =
    context?.recipientEmail || process.env.ZENDIT_USERNAME || "sri@techladder.io";
  const nameParts = (context?.recipientName || "").trim().split(/\s+/).filter(Boolean);
  const firstName = nameParts[0] || "Valued";
  const lastName = nameParts.slice(1).join(" ") || "Customer";
  const senderParts = (context?.senderName || "").trim().split(/\s+/).filter(Boolean);
  const senderFirst = senderParts[0] || firstName;
  const senderLast = senderParts.slice(1).join(" ") || lastName;

  return requiredKeys.map((key) => {
    switch (key) {
      case "recipient.firstName":
        return { key, value: firstName };
      case "sender.firstName":
        return { key, value: senderFirst };
      case "recipient.lastName":
        return { key, value: lastName };
      case "sender.lastName":
        return { key, value: senderLast };
      case "recipient.email":
      case "sender.email":
        return { key, value: defaultEmail };
      case "recipient.msisdn":
      case "recipient.phoneNumber":
      case "sender.msisdn":
      case "sender.phoneNumber":
        return { key, value: "+15552345678" };
      case "recipient.country":
      case "sender.country":
        return { key, value: "US" };
      default:
        return { key, value: "BuyGiftCards" };
    }
  });
}

// Hand-maintained entries above take precedence over the generated live-catalog map.
const ZENDIT_OFFERS: Record<string, ZenditOfferSpec> = {
  ...GENERATED_ZENDIT_OFFERS,
  ...BRAND_TO_ZENDIT_OFFER,
};

/** True if the brand can actually be fulfilled (house card or has a Zendit offer). */
export function isFulfillableBrand(slug: string): boolean {
  if (HOUSE_BRAND_SLUGS.includes(slug)) return true;
  // If Tango is configured, check if brand has a Tango UTID mapping
  if (isTangoActive()) {
    const utid = BRAND_TO_TANGO_UTID[slug];
    if (utid) return true;
  }
  const spec = ZENDIT_OFFERS[slug];
  return Boolean(spec && (spec.fixedOffers || (spec.rangeOfferId && spec.rangeOfferId !== "HOUSE_SWAP")));
}

export function isTangoActive(): boolean {
  return Boolean(
    process.env.TANGO_PLATFORM_NAME &&
      process.env.TANGO_PLATFORM_KEY &&
      process.env.TANGO_ACCOUNT_IDENTIFIER &&
      process.env.TANGO_CUSTOMER_IDENTIFIER
  );
}

export class ZenditUnfulfillableError extends Error {}

export const ZENDIT_API_URL = "https://api.zendit.io/v1";

export class ZenditProvider implements GiftCardProvider {
  private apiKey: string;
  private baseUrl: string;

  constructor() {
    // Environment is chosen purely by the key: `sand_...` = Zendit sandbox, `prod_...` = live.
    // Nothing is hard-coded, so a missing key can never silently fall through to live purchases.
    const key = process.env.ZENDIT_API_KEY;
    if (!key) throw new Error("ZENDIT_API_KEY is not set — required for ZenditProvider");
    this.apiKey = key;
    this.baseUrl = (process.env.ZENDIT_API_BASE_URL || ZENDIT_API_URL).replace(/\/+$/, "");
  }

  async issue({
    brandSlug,
    amountCents,
    recipientEmail,
    recipientName,
    senderName,
  }: IssueCardParams): Promise<IssuedCard> {
    const isHouseBrand = HOUSE_BRAND_SLUGS.includes(brandSlug);
    const spec = ZENDIT_OFFERS[brandSlug];

    const dollars = Math.max(1, Math.round(amountCents / 100));

    // House / multi-brand cards are redeemed later on /redeem for a real brand, so no
    // supplier voucher is purchased up front — just issue a card number + PIN.
    if (isHouseBrand) {
      const code = generateDemoCode();
      const pin = generateDemoPin();
      writeTransactionLog({
        phase: "PROCESS_COMPLETE",
        process: `ZenditProvider.issue(${brandSlug}, $${dollars})`,
        details: { brandSlug, amountCents, note: "House card issued; supplier voucher is purchased at redemption." },
      });
      return { code, pin, isDemo: false };
    }

    let offerId: string | undefined;
    let isRange = false;
    const rangeValueCents = amountCents;

    if (spec) {
      if (spec.fixedOffers && spec.fixedOffers[dollars]) {
        offerId = spec.fixedOffers[dollars];
      } else if (spec.rangeOfferId && spec.rangeOfferId !== "HOUSE_SWAP") {
        offerId = spec.rangeOfferId;
        isRange = true;
      }
    }

    // Never substitute a different brand/denomination: a customer who paid for X must get X.
    if (!offerId) {
      const msg = `No Zendit offer for brand "${brandSlug}" at $${dollars} — refusing to issue a different card.`;
      writeTransactionLog({ phase: "PROCESS_ERROR", process: `ZenditProvider.issue(${brandSlug})`, error: msg });
      throw new ZenditUnfulfillableError(msg);
    }

    const transactionId = `bgc-${Date.now()}-${Math.random().toString(36).slice(2, 9)}`;
    const fields = buildZenditRequiredFields(spec?.requiredFields, {
      recipientEmail,
      recipientName,
      senderName,
    });

    const payload: Record<string, unknown> = {
      transactionId,
      offerId,
      fields,
    };

    if (isRange) {
      payload.value = {
        type: "ZEND",
        value: rangeValueCents,
      };
    }

    writeTransactionLog({
      phase: "PROCESS_START",
      process: `ZenditProvider.issue(${brandSlug}, $${dollars})`,
      transactionId,
      apiUrl: `${this.baseUrl}/vouchers/purchases`,
      details: {
        brandSlug,
        amountCents,
        offerId,
        priceType: isRange ? "RANGE" : "FIXED",
        requiredFields: fields,
        recipientEmail,
        recipientName,
      },
    });

    const { res: createRes, rawText: createErrBody } = await loggedFetch({
      process: "ZenditProvider.createVoucherPurchase",
      transactionId,
      url: `${this.baseUrl}/vouchers/purchases`,
      method: "POST",
      headers: {
        Authorization: `Bearer ${this.apiKey}`,
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      bodyObj: payload,
    });

    if (!createRes.ok) {
      throw new Error(`Zendit POST /vouchers/purchases failed (${createRes.status}): ${createErrBody}`);
    }

    // Poll GET /vouchers/purchases/{transactionId} until status is DONE or FAILED
    for (let attempt = 1; attempt <= 15; attempt++) {
      if (attempt > 1) {
        await new Promise((r) => setTimeout(r, 750));
      }
      const { res: pollRes, data: tx, rawText: pollErr } = await loggedFetch({
        process: `ZenditProvider.pollVoucherPurchase (attempt #${attempt})`,
        transactionId,
        url: `${this.baseUrl}/vouchers/purchases/${encodeURIComponent(transactionId)}`,
        method: "GET",
        headers: {
          Authorization: `Bearer ${this.apiKey}`,
          Accept: "application/json",
        },
      });

      if (!pollRes.ok) {
        throw new Error(`Zendit GET /vouchers/purchases/${transactionId} failed (${pollRes.status}): ${pollErr}`);
      }

      if (tx.status === "FAILED") {
        const errMsg = tx.error?.message || tx.error?.description || tx.error?.code || "Transaction FAILED";
        writeTransactionLog({
          phase: "PROCESS_ERROR",
          process: `ZenditProvider.issue(${brandSlug})`,
          transactionId,
          error: errMsg,
          details: tx.error,
        });
        throw new Error(`Zendit voucher purchase failed: ${errMsg}`);
      }

      if (tx.status === "DONE") {
        const receipt = tx.receipt || {};
        const zenditCode =
          receipt.redemptionUrl ||
          receipt.voucherId ||
          receipt.epin ||
          tx.confirmation?.externalReferenceId ||
          tx.confirmation?.confirmationNumber;
        const zenditPin = receipt.redemptionUrl
          ? receipt.epin || receipt.voucherId || ""
          : receipt.epin || "";

        if (!zenditCode) {
          throw new Error(`Zendit transaction DONE but receipt is missing voucher credential: ${JSON.stringify(tx)}`);
        }

        // For House Choice Cards (`buygiftcards`, `one4all`, `holidayfavorites`), issue a 16-digit
        // card number + 8-digit PIN so the recipient can enter it on `/redeem` to swap for any brand,
        // while still backed by the real Zendit transaction above.
        const finalCode = isHouseBrand ? generateDemoCode() : String(zenditCode);
        const finalPin = isHouseBrand ? generateDemoPin() : String(zenditPin);

        writeTransactionLog({
          phase: "PROCESS_COMPLETE",
          process: `ZenditProvider.issue(${brandSlug}, $${dollars})`,
          transactionId,
          apiUrl: `${this.baseUrl}/vouchers/purchases/${transactionId}`,
          details: {
            brandSlug,
            offerId,
            status: tx.status,
            costCents: tx.cost,
            sendCents: tx.send,
            deliveryType: receipt.deliveryType,
            confirmationNumber: receipt.confirmationNumber,
            zenditVoucherUrl: String(zenditCode),
            issuedCode: finalCode,
          },
        });

        return {
          code: finalCode,
          pin: finalPin,
          isDemo: false,
          zenditTransactionId: transactionId,
          zenditOfferId: offerId,
        };
      }
    }

    throw new Error(`Zendit transaction ${transactionId} timed out waiting for DONE status`);
  }
}

class HybridZenditProvider implements GiftCardProvider {
  constructor(
    private zendit: GiftCardProvider,
    private fallback: GiftCardProvider
  ) {}

  async issue(params: IssueCardParams): Promise<IssuedCard> {
    try {
      return await this.zendit.issue(params);
    } catch (err) {
      // Never swap in placeholder codes for a brand we can't supply.
      if (err instanceof ZenditUnfulfillableError) throw err;
      const msg = err instanceof Error ? err.message : String(err);
      console.warn(
        `[giftcard-provider] Zendit issue failed for "${params.brandSlug}" (${msg}) — falling back to secondary provider.`
      );
      return this.fallback.issue(params);
    }
  }
}

