export function getZenditOffersForCountry(
  country: CountryCode = resolveCountryFromHostOrEnv()
): Record<string, ZenditOfferSpec> {
  if (country === "CA") return ZENDIT_CA_OFFERS;
  if (country === "SG") return ZENDIT_SG_OFFERS;
  if (country === "AU") return ZENDIT_AU_OFFERS;
  return ZENDIT_OFFERS;
}

/**
 * Returns which primary provider is chosen via country-aware environment properties:
 * GIFTCARD_PROVIDER="zendit" | "tango" (or CA_GIFTCARD_PROVIDER / env-ca, SG_GIFTCARD_PROVIDER / env-sg).
 */
export function getSelectedProviderName(country: CountryCode = resolveCountryFromHostOrEnv()): "zendit" | "tango" {
  const chosen = getCountryEnv("GIFTCARD_PROVIDER", country, "zendit").toLowerCase().trim();
  if (chosen === "tango") return "tango";
  return "zendit";
}

/** True if the brand can actually be fulfilled (house card or has an offer in the active provider). */
export function isFulfillableBrand(slug: string, country: CountryCode = resolveCountryFromHostOrEnv()): boolean {
  if (HOUSE_BRAND_SLUGS.includes(slug)) return true;
  
  const provider = getSelectedProviderName(country);
  if (provider === "tango" && isTangoActive(country)) {
    return Boolean(BRAND_TO_TANGO_UTID[slug]);
  }

  const offersMap = getZenditOffersForCountry(country);
  const spec = offersMap[slug];
  return Boolean(spec && (spec.fixedOffers || (spec.rangeOfferId && spec.rangeOfferId !== "HOUSE_SWAP")));
}

export function isTangoActive(country: CountryCode = resolveCountryFromHostOrEnv()): boolean {
  return Boolean(
    getCountryEnv("TANGO_PLATFORM_NAME", country) &&
      getCountryEnv("TANGO_PLATFORM_KEY", country) &&
      getCountryEnv("TANGO_ACCOUNT_IDENTIFIER", country) &&
      getCountryEnv("TANGO_CUSTOMER_IDENTIFIER", country)
  );
}

export class ZenditUnfulfillableError extends Error {}

export const ZENDIT_API_URL = "https://api.zendit.io/v1";

export class ZenditProvider implements GiftCardProvider {
  private apiKey: string;
  private baseUrl: string;
  private country: CountryCode;

  constructor(country: CountryCode = resolveCountryFromHostOrEnv()) {
    // Environment is chosen purely by the key: `sand_...` = Zendit sandbox, `prod_...` = live.
    // Nothing is hard-coded, so a missing key can never silently fall through to live purchases.
    const key = getCountryEnv("ZENDIT_API_KEY", country);
    if (!key) throw new Error(`ZENDIT_API_KEY is not set — required for ZenditProvider (${country})`);
    this.apiKey = key;
    this.baseUrl = getCountryEnv("ZENDIT_API_BASE_URL", country, ZENDIT_API_URL).replace(/\/+$/, "");
    this.country = country;
  }

  async issue({
    brandSlug,
    amountCents,
    recipientEmail,
    recipientName,
    senderName,
  }: IssueCardParams): Promise<IssuedCard> {
    const isHouseBrand = HOUSE_BRAND_SLUGS.includes(brandSlug);
    const offersMap = getZenditOffersForCountry(this.country);
    const spec = offersMap[brandSlug] || ZENDIT_OFFERS[brandSlug];

    const dollars = Math.max(1, Math.round(amountCents / 100));

    // House / multi-brand cards are redeemed later on /redeem for a real brand, so no
    // supplier voucher is purchased up front — just issue a card number + PIN.
    if (isHouseBrand) {
      const code = generateDemoCode();
      const pin = generateDemoPin();
      writeTransactionLog({
        phase: "PROCESS_COMPLETE",
        process: `ZenditProvider.issue(${brandSlug}, $${dollars})`,
        details: { brandSlug, amountCents, country: this.country, note: "House card issued; supplier voucher is purchased at redemption." },
      });
      return { code, pin, isDemo: false };
    }

    let offerId: string | undefined;
    let isRange = false;
    const rangeValueCents = amountCents;

    if (spec) {
      if (spec.fixedOffers && spec.fixedOffers[dollars]) {
        offerId = spec.fixedOffers[dollars];
      } else if (spec.rangeOfferId && spec.rangeOfferId !== "HOUSE_SWAP") {
        offerId = spec.rangeOfferId;
        isRange = true;
      }
    }

    // Never substitute a different brand/denomination: a customer who paid for X must get X.
    if (!offerId) {
      const msg = `No Zendit offer (${this.country}) for brand "${brandSlug}" at $${dollars} — refusing to issue a different card.`;
      writeTransactionLog({ phase: "PROCESS_ERROR", process: `ZenditProvider.issue(${brandSlug})`, error: msg });
      throw new ZenditUnfulfillableError(msg);
    }

    const transactionId = `bgc-${Date.now()}-${Math.random().toString(36).slice(2, 9)}`;
    const fields = buildZenditRequiredFields(spec?.requiredFields, {
      recipientEmail,
      recipientName,
      senderName,
      country: this.country,
    });

    const payload: Record<string, unknown> = {
      transactionId,
      offerId,
      fields,
    };

    if (isRange) {
      payload.value = {
        type: "ZEND",
        value: rangeValueCents,
      };
    }

    writeTransactionLog({
      phase: "PROCESS_START",
      process: `ZenditProvider.issue(${brandSlug}, $${dollars})`,
      transactionId,
      apiUrl: `${this.baseUrl}/vouchers/purchases`,
      details: {
        brandSlug,
        amountCents,
        offerId,
        priceType: isRange ? "RANGE" : "FIXED",
        requiredFields: fields,
        recipientEmail,
        recipientName,
      },
    });

    const { res: createRes, rawText: createErrBody } = await loggedFetch({
      process: "ZenditProvider.createVoucherPurchase",
      transactionId,
      url: `${this.baseUrl}/vouchers/purchases`,
      method: "POST",
      headers: {
        Authorization: `Bearer ${this.apiKey}`,
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      bodyObj: payload,
    });

    if (!createRes.ok) {
      throw new Error(`Zendit POST /vouchers/purchases failed (${createRes.status}): ${createErrBody}`);
    }

    // Poll GET /vouchers/purchases/{transactionId} until status is DONE or FAILED
    for (let attempt = 1; attempt <= 15; attempt++) {
      if (attempt > 1) {
        await new Promise((r) => setTimeout(r, 750));
      }
      const { res: pollRes, data: tx, rawText: pollErr } = await loggedFetch({
        process: `ZenditProvider.pollVoucherPurchase (attempt #${attempt})`,
        transactionId,
        url: `${this.baseUrl}/vouchers/purchases/${encodeURIComponent(transactionId)}`,
        method: "GET",
        headers: {
          Authorization: `Bearer ${this.apiKey}`,
          Accept: "application/json",
        },
      });

      if (!pollRes.ok) {
        throw new Error(`Zendit GET /vouchers/purchases/${transactionId} failed (${pollRes.status}): ${pollErr}`);
      }

      if (tx.status === "FAILED") {
        const errMsg = tx.error?.message || tx.error?.description || tx.error?.code || "Transaction FAILED";
        writeTransactionLog({
          phase: "PROCESS_ERROR",
          process: `ZenditProvider.issue(${brandSlug})`,
          transactionId,
          error: errMsg,
          details: tx.error,
        });
        throw new Error(`Zendit voucher purchase failed: ${errMsg}`);
      }

      if (tx.status === "DONE") {
        const receipt = tx.receipt || {};
        const zenditCode =
          receipt.redemptionUrl ||
          receipt.voucherId ||
          receipt.epin ||
          tx.confirmation?.externalReferenceId ||
          tx.confirmation?.confirmationNumber;
        const zenditPin = receipt.redemptionUrl
          ? receipt.epin || receipt.voucherId || ""
          : receipt.epin || "";

        if (!zenditCode) {
          throw new Error(`Zendit transaction DONE but receipt is missing voucher credential: ${JSON.stringify(tx)}`);
        }

        // For House Choice Cards (`buygiftcards`, `one4all`, `holidayfavorites`), issue a 16-digit
        // card number + 8-digit PIN so the recipient can enter it on `/redeem` to swap for any brand,
        // while still backed by the real Zendit transaction above.
        const finalCode = isHouseBrand ? generateDemoCode() : String(zenditCode);
        const finalPin = isHouseBrand ? generateDemoPin() : String(zenditPin);

        writeTransactionLog({
          phase: "PROCESS_COMPLETE",
          process: `ZenditProvider.issue(${brandSlug}, $${dollars})`,
          transactionId,
          apiUrl: `${this.baseUrl}/vouchers/purchases/${transactionId}`,
          details: {
            brandSlug,
            offerId,
            status: tx.status,
            costCents: tx.cost,
            sendCents: tx.send,
            deliveryType: receipt.deliveryType,
            confirmationNumber: receipt.confirmationNumber,
            zenditVoucherUrl: String(zenditCode),
            issuedCode: finalCode,
          },
        });

        return {
          code: finalCode,
          pin: finalPin,
          isDemo: false,
          zenditTransactionId: transactionId,
          zenditOfferId: offerId,
        };
      }
    }

    throw new Error(`Zendit transaction ${transactionId} timed out waiting for DONE status`);
  }
}

class HybridZenditProvider implements GiftCardProvider {
  constructor(
    private zendit: GiftCardProvider,
    private fallback: GiftCardProvider
  ) {}

  async issue(params: IssueCardParams): Promise<IssuedCard> {
    try {
      return await this.zendit.issue(params);
    } catch (err) {
      // Never swap in placeholder codes or silently fall back to Tango when Zendit is the active primary provider.
      // Surface the exact Zendit error so the caller/logs see why Zendit failed instead of a confusing Tango error.
      if (err instanceof ZenditUnfulfillableError) throw err;
      const msg = err instanceof Error ? err.message : String(err);
      console.warn(
        `[giftcard-provider] Zendit issue failed for "${params.brandSlug}": ${msg}`
      );
      throw err;
    }
  }
}

// ---------------------------------------------------------------------------
// Factory — switchable via GIFTCARD_PROVIDER="zendit" | "tango" per country
// ---------------------------------------------------------------------------

export function buildProvider(country: CountryCode = resolveCountryFromHostOrEnv()): GiftCardProvider {
  const demo = new DemoGiftCardProvider();
  const selected = getSelectedProviderName(country);

  const hasTangoConfig = isTangoActive(country);
  const tangoProvider = hasTangoConfig ? new TangoCardProvider(country) : null;

  const zenditKey = getCountryEnv("ZENDIT_API_KEY", country);
  const hasZenditConfig = Boolean(zenditKey);
  const zenditProvider = hasZenditConfig ? new ZenditProvider(country) : null;

  // 1. If Tango is explicitly selected as primary:
  if (selected === "tango") {
    if (tangoProvider) {
      const tangoBaseUrl = getCountryEnv("TANGO_API_BASE_URL", country, "https://integration-api.tangocard.com/raas/v2");
      const isSandboxCreds =
        getCountryEnv("TANGO_PLATFORM_NAME", country) === "QAPlatform2" ||
        tangoBaseUrl.includes("integration-api");
      const mode = isSandboxCreds ? "SANDBOX" : "PRODUCTION";
      console.log(
        `[giftcard-provider:${country}] Using TangoCardProvider [${mode}] as PRIMARY (GIFTCARD_PROVIDER=tango) ` +
          `(${Object.keys(BRAND_TO_TANGO_UTID).length} brands mapped, account: ${getCountryEnv("TANGO_ACCOUNT_IDENTIFIER", country)})`
      );
      return new HybridGiftCardProvider(tangoProvider, demo);
    } else {
      console.warn(`[giftcard-provider:${country}] GIFTCARD_PROVIDER=tango requested, but Tango credentials are not fully configured.`);
    }
  }

  // 2. Default or explicitly chosen: Zendit as primary
  if (zenditProvider) {
    const mappedCount = Object.keys(getZenditOffersForCountry(country)).length;
    const mode = zenditKey.startsWith("prod_") ? "LIVE" : "SANDBOX";
    console.log(
      `[giftcard-provider:${country}] Using ZenditProvider [${mode}] as PRIMARY (GIFTCARD_PROVIDER=${selected}) ` +
        `(${mappedCount} brands mapped, account: ${getCountryEnv("ZENDIT_USERNAME", country, "sri@techladder.io")})`
    );
    return zenditProvider;
  }

  // 3. Fall back to Tango if Zendit is not set up
  if (tangoProvider) {
    const tangoBaseUrl = getCountryEnv("TANGO_API_BASE_URL", country, "https://api.tangocard.com/raas/v2");
    const mode = tangoBaseUrl.includes("integration-api") ? "SANDBOX" : "PRODUCTION";
    console.log(
      `[giftcard-provider:${country}] Falling back to TangoCardProvider [${mode}] ` +
        `(${Object.keys(BRAND_TO_TANGO_UTID).length} brands mapped)`
    );
    return new HybridGiftCardProvider(tangoProvider, demo);
  }

  // 4. Demo fallback — non-redeemable codes only.
  console.warn(`[giftcard-provider:${country}] No live provider configured — using DemoGiftCardProvider (non-redeemable codes)`);
  return demo;
}

export const giftCardProvider: GiftCardProvider = buildProvider();
