function requireEnv(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is not set — required for TangoCardProvider`);
  return value;
}

export class TangoCardProvider implements GiftCardProvider {
  private baseUrl: string;
  private platformName: string;
  private platformKey: string;
  private accountIdentifier: string;
  private customerIdentifier: string;

  constructor() {
    // Sandbox vs production is just a different base URL in Tango's API —
    // defaults to sandbox so you can't accidentally hit production by
    // forgetting to set this.
    this.baseUrl = process.env.TANGO_API_BASE_URL || "https://integration-api.tangocard.com/raas/v2";
    this.platformName = requireEnv("TANGO_PLATFORM_NAME");
    this.platformKey = requireEnv("TANGO_PLATFORM_KEY");
    this.accountIdentifier = requireEnv("TANGO_ACCOUNT_IDENTIFIER");
    this.customerIdentifier = requireEnv("TANGO_CUSTOMER_IDENTIFIER");
  }

  async issue({ brandSlug, amountCents }: { brandSlug: string; amountCents: number }): Promise<IssuedCard> {
    const mapping = BRAND_TO_TANGO_UTID[brandSlug];
    if (!mapping) {
      throw new Error(
        `No Tango Card utid mapped for brand "${brandSlug}". Run \`npm run tango:match\` and add it to BRAND_TO_TANGO_UTID.`
      );
    }

    let utid: string;
    if (typeof mapping === "string") {
      utid = mapping; // variable-value card, works for any amount
    } else {
      const dollars = amountCents / 100;
      const found = mapping[dollars];
      if (!found) {
        throw new Error(
          `Brand "${brandSlug}" has no Tango utid for $${dollars} — available: ${Object.keys(mapping).join(", ")}`
        );
      }
      utid = found;
    }

    const auth = Buffer.from(`${this.platformName}:${this.platformKey}`).toString("base64");
    const res = await fetch(`${this.baseUrl}/orders`, {
      method: "POST",
      headers: {
        Authorization: `Basic ${auth}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        accountIdentifier: this.accountIdentifier,
        customerIdentifier: this.customerIdentifier,
        amount: amountCents / 100,
        utid,
        sendEmail: false, // we deliver the code ourselves via our own email
      }),
    });

    if (!res.ok) {
      const body = await res.text().catch(() => "");
      throw new Error(`Tango Card order failed (${res.status}): ${body}`);
    }

    const data = await res.json();
    // Verified against a real sandbox order (Starbucks, $5): the response
    // has reward.credentialList = [{ label, value, type, credentialType }],
    // and credentialType varies by brand/reward — card-number brands use
    // "cardNumber"/"pin", others (confirmed: Starbucks) deliver a
    // "redemptionUrl" instead with no PIN at all. Handle both rather than
    // assuming one shape.
    type Credential = { credentialType?: string; value?: string };
    const credentialList: Credential[] = data?.reward?.credentialList ?? [];

    const cardNumber = credentialList.find((c) => c.credentialType === "cardNumber")?.value;
    const pin = credentialList.find((c) => c.credentialType === "pin")?.value ?? "";
    const redemptionUrl = credentialList.find(
      (c) => c.credentialType === "redemptionUrl" || c.credentialType === "claimUrl"
    )?.value;

    const code = cardNumber ?? redemptionUrl ?? credentialList[0]?.value;
    if (!code) {
      throw new Error(`Tango Card order succeeded but no redeemable code was found in the response: ${JSON.stringify(data)}`);
    }

    return { code, pin, isDemo: false };
  }
}

// Per-brand, not global: only ~66 of our 165 catalog brands have a Tango
// utid mapped (sandbox catalog is a curated subset — see the comment on
// BRAND_TO_TANGO_UTID). A single global switch would mean checkout starts
// throwing entirely for every unmapped brand the moment Tango is
// configured. Instead: use Tango when a brand is mapped, fall back to Demo
// (loudly logged) when it isn't — the resulting code is still marked
// isDemo, which the order detail page and email already surface clearly.
class HybridGiftCardProvider implements GiftCardProvider {
  constructor(
    private tango: GiftCardProvider,
    private demo: GiftCardProvider
  ) {}

  async issue(params: { brandSlug: string; amountCents: number }): Promise<IssuedCard> {
    if (BRAND_TO_TANGO_UTID[params.brandSlug]) {
      return this.tango.issue(params);
    }
    console.warn(
      `[giftcard-provider] "${params.brandSlug}" has no Tango mapping — issuing a non-redeemable demo code instead of real fulfillment.`
    );
    return this.demo.issue(params);
  }
}

